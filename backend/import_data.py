def run():
    conn = get_connection()
    if not conn:
        print("Erro de conexão DB")
        return

    # Processing CSV string
    lines = raw_data.strip().split('\n')
    # skip header
    lines = lines[1:]

    try:
        with conn.cursor() as cursor:
            # Drop constraint if exists? No, we just insert.
            
            # 1. Fetch sections to map name -> ID
            cursor.execute("SELECT ID, Nome FROM Secoes")
            secoes = {row[1].upper(): row[0] for row in cursor.fetchall()}
            
            # If any section is missing we could insert it, but let's assume the DB has them.
            
            for index, line in enumerate(lines):
                parts = line.split('\t')
                
                # To prevent IndexErrors if line is malformed:
                codigo = parts[0].strip() if len(parts) > 0 else ""
                secao_nome = parts[1].strip() if len(parts) > 1 else ""
                descricao = parts[2].strip() if len(parts) > 2 else ""
                
                estoque_str = parts[3].strip() if len(parts) > 3 else "0"
                if estoque_str == "":
                    estoque_str = "0"
                # Replacing dot with empty and comma with dot if formatted like 4.000 (which might be 4000)
                estoque_str = estoque_str.replace('.', '').replace(',', '.')
                estoque_val = float(estoque_str) if estoque_str else 0.0
                
                if not codigo: continue
                
                secao_id = None
                if secao_nome:
                    sn_upper = secao_nome.upper()
                    if sn_upper in secoes:
                        secao_id = secoes[sn_upper]
                    else:
                        # Insert new Section if not exists
                        cursor.execute("INSERT INTO Secoes (Nome) VALUES (%s)", (secao_nome,))
                        secao_id = cursor.lastrowid
                        secoes[sn_upper] = secao_id

                # Insert Product
                sql_prod = """
                    INSERT INTO Produtos (Codigo_ERP_Principal, Nome, Secao_ID, Estoque_Atual, Custo)
                    VALUES (%s, %s, %s, %s, 0)
                    ON DUPLICATE KEY UPDATE 
                        Nome = VALUES(Nome),
                        Secao_ID = VALUES(Secao_ID),
                        Estoque_Atual = VALUES(Estoque_Atual)
                """
                cursor.execute(sql_prod, (codigo, descricao, secao_id, estoque_val))
                
                # Make sure Estoque_Loja table is populated for this product for Loja_ID = 1 (Main/BCS) so it shows up in matrix properly
                sql_est = """
                    INSERT INTO Estoque_Loja (Produto_ID, Loja_ID, Estoque_Maximo) 
                    VALUES (%s, 1, 0)
                    ON DUPLICATE KEY UPDATE Produto_ID=Produto_ID
                """
                cursor.execute(sql_est, (codigo,))
            
            conn.commit()
            print(f"Sucesso! {len(lines)} produtos foram importados/atualizados.")
    except Exception as e:
        print(f"Erro ao importar: {e}")
    finally:
        conn.close()

if __name__ == "__main__":
    run()
